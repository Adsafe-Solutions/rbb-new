/* Cloudflare Pages' own formats for what the build already decides
   (docs/HOST_CONFIGURATION.md — the contract any host must meet). The
   prerender writes them into dist/ beside the pages, from the same data
   as build-meta/redirects.json and build-meta/security-headers.json, which
   stay the source of truth for every other host and check.

     dist/_redirects  every permanent redirect. The reference server
                      (server/dev-server.mjs) matches an address with or
                      without its trailing slash, and redirects before
                      serving any file — Cloudflare Pages always follows a
                      redirect, whatever the asset, so each one is written
                      for both forms.
     dist/_headers    the security headers on every response; the
                      immutable cache rule on /assets/* REPLACING the page
                      rule's Cache-Control (Cloudflare joins repeated
                      headers with a comma, so the page rule is detached
                      first); preview deployments (*.pages.dev) noindex;
                      HSTS only on the verified production origin, never on
                      a preview or a stand-in host.

   Anything Cloudflare cannot express as given fails the build: a rule is
   never silently dropped. Limits: docs for Cloudflare Pages redirects and
   headers (2,000 static redirects; 100 header rules; 2,000 characters a
   line). */

const MAX_REDIRECTS = 2000;
const MAX_HEADER_RULES = 100;
const MAX_LINE = 2000;
const STATUSES = new Set([301, 302, 303, 307, 308]);
const PREVIEW_HOSTS = ["https://:project.pages.dev/*", "https://:version.:project.pages.dev/*"];

const problem = (message) => {
  throw new Error(`Cloudflare Pages: ${message}`);
};

/* `redirects`: [{ from, to, status }], as build-meta/redirects.json. */
export function cloudflareRedirects(redirects) {
  const lines = ["# Generated by scripts/prerender.mjs from build-meta/redirects.json — do not edit."];
  for (const { from, to, status } of redirects) {
    if (typeof from !== "string" || !from.startsWith("/") || /\s/.test(from)) problem(`redirect source ${JSON.stringify(from)} is not a plain site path`);
    if (typeof to !== "string" || !to || /\s/.test(to)) problem(`redirect target for ${from} cannot be written as one token`);
    if (!STATUSES.has(status)) problem(`redirect ${from} has status ${status}, which Cloudflare Pages does not support`);
    const bare = from.replace(/\/+$/, "") || "/";
    lines.push(`${bare} ${to} ${status}`);
    if (bare !== "/") lines.push(`${bare}/ ${to} ${status}`);
  }
  if (lines.length - 1 > MAX_REDIRECTS) problem(`${lines.length - 1} redirects exceed Cloudflare Pages' ${MAX_REDIRECTS}`);
  return lines.join("\n") + "\n";
}

/* `headers`: the `headers` object of build-meta/security-headers.json —
   "/*" (every response), further path rules, and `productionHttpsOnly`.
   `productionOrigin`: the verified production origin (VITE_SITE_URL), or
   null — then HSTS is not written at all. */
export function cloudflareHeaders(headers, { productionOrigin = null } = {}) {
  const { productionHttpsOnly = {}, ...rules } = headers;
  const all = rules["/*"] ?? {};
  const blocks = [];
  for (const [path, set] of Object.entries(rules)) {
    if (!path.startsWith("/")) problem(`header rule ${JSON.stringify(path)} is not a path pattern`);
    const lines = [];
    // A narrower rule replaces, never joins, a header the page rule already sets.
    if (path !== "/*") for (const name of Object.keys(set)) if (name in all) lines.push(`! ${name}`);
    for (const [name, value] of Object.entries(set)) lines.push(`${name}: ${value}`);
    blocks.push([path, lines]);
  }
  for (const host of PREVIEW_HOSTS) blocks.push([host, ["X-Robots-Tag: noindex, nofollow"]]);
  const hsts = Object.entries(productionHttpsOnly).map(([name, value]) => `${name}: ${value}`);
  if (hsts.length && productionOrigin) blocks.push([`${productionOrigin}/*`, hsts]);

  if (blocks.length > MAX_HEADER_RULES) problem(`${blocks.length} header rules exceed Cloudflare Pages' ${MAX_HEADER_RULES}`);
  const out = ["# Generated by scripts/prerender.mjs from build-meta/security-headers.json — do not edit."];
  if (hsts.length && !productionOrigin) out.push("# Strict-Transport-Security is not written: no verified production origin (VITE_SITE_URL).");
  for (const [pattern, lines] of blocks) {
    out.push(pattern, ...lines.map((l) => `  ${l}`));
  }
  for (const line of out) if (line.length > MAX_LINE) problem(`a header line is ${line.length} characters (limit ${MAX_LINE}): ${line.slice(0, 60)}…`);
  return out.join("\n") + "\n";
}
